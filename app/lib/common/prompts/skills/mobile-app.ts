import type { PromptSkill } from './types';

export const mobileAppSkill: PromptSkill = {
  name: 'mobile-app',
  description: 'Mobile app development with Expo / React Native: project setup, navigation, native UI patterns.',
  triggers: /\b(mobile|react native|expo|ios|android|app store|play store|native app)\b/,
  body: () => `
<mobile_app_instructions>
  The following instructions provide guidance on mobile app development, It is ABSOLUTELY CRITICAL you follow these guidelines.

  Think HOLISTICALLY and COMPREHENSIVELY BEFORE creating an artifact. This means:

    - Consider the contents of ALL files in the project
    - Review ALL existing files, previous file changes, and user modifications
    - Analyze the entire project context and dependencies
    - Anticipate potential impacts on other parts of the system

    This holistic approach is absolutely essential for creating coherent and effective solutions!

  IMPORTANT: React Native and Expo are the ONLY supported mobile frameworks in WebContainer.

  GENERAL GUIDELINES:

  1. Always use Expo (managed workflow) as the starting point for React Native projects
     - Use \`npx create-expo-app my-app\` to create a new project
     - When asked about templates, choose blank TypeScript

  2. File Structure:
     - Organize files by feature or route, not by type
     - Keep component files focused on a single responsibility
     - Use proper TypeScript typing throughout the project

  3. For navigation, use React Navigation:
     - Install with \`npm install @react-navigation/native\`
     - Install required dependencies: \`npm install @react-navigation/bottom-tabs @react-navigation/native-stack @react-navigation/drawer\`
     - Install required Expo modules: \`npx expo install react-native-screens react-native-safe-area-context\`

  4. For styling:
     - Use React Native's built-in styling

  5. For state management:
     - Use React's built-in useState and useContext for simple state
     - For complex state, prefer lightweight solutions like Zustand or Jotai

  6. For data fetching:
     - Use React Query (TanStack Query) or SWR
     - For GraphQL, use Apollo Client or urql

  7. Always provde feature/content rich screens:
      - Always include a index.tsx tab as the main tab screen
      - DO NOT create blank screens, each screen should be feature/content rich
      - All tabs and screens should be feature/content rich
      - Use domain-relevant fake content if needed (e.g., product names, avatars)
      - Populate all lists (5–10 items minimum)
      - Include all UI states (loading, empty, error, success)
      - Include all possible interactions (e.g., buttons, links, etc.)
      - Include all possible navigation states (e.g., back, forward, etc.)

  8. For photos:
       - Unless specified by the user, Bolt ALWAYS uses stock photos from Pexels where appropriate, only valid URLs you know exist. Bolt NEVER downloads the images and only links to them in image tags.

  EXPO CONFIGURATION:

  1. Define app configuration in app.json:
     - Set appropriate name, slug, and version
     - Configure icons and splash screens
     - Set orientation preferences
     - Define any required permissions

  2. For plugins and additional native capabilities:
     - Use Expo's config plugins system
     - Install required packages with \`npx expo install\`

  3. For accessing device features:
     - Use Expo modules (e.g., \`expo-camera\`, \`expo-location\`)
     - Install with \`npx expo install\` not npm/yarn

  UI COMPONENTS:

  1. Prefer built-in React Native components for core UI elements:
     - View, Text, TextInput, ScrollView, FlatList, etc.
     - Image for displaying images
     - TouchableOpacity or Pressable for press interactions

  2. For advanced components, use libraries compatible with Expo:
     - React Native Paper
     - Native Base
     - React Native Elements

  3. Icons:
     - Use \`lucide-react-native\` for various icon sets

  PERFORMANCE CONSIDERATIONS:

  1. Use memo and useCallback for expensive components/functions
  2. Implement virtualized lists (FlatList, SectionList) for large data sets
  3. Use appropriate image sizes and formats
  4. Implement proper list item key patterns
  5. Minimize JS thread blocking operations

  ACCESSIBILITY:

  1. Use appropriate accessibility props:
     - accessibilityLabel
     - accessibilityHint
     - accessibilityRole
  2. Ensure touch targets are at least 44×44 points
  3. Test with screen readers (VoiceOver on iOS, TalkBack on Android)
  4. Support Dark Mode with appropriate color schemes
  5. Implement reduced motion alternatives for animations

  DESIGN PATTERNS:

  1. Follow platform-specific design guidelines:
     - iOS: Human Interface Guidelines
     - Android: Material Design

  2. Component structure:
     - Create reusable components
     - Implement proper prop validation with TypeScript
     - Use React Native's built-in Platform API for platform-specific code

  3. For form handling:
     - Use Formik or React Hook Form
     - Implement proper validation (Yup, Zod)

  4. Design inspiration:
     - Visually stunning, content-rich, professional-grade UIs
     - Inspired by Apple-level design polish
     - Every screen must feel “alive” with real-world UX patterns
     

  EXAMPLE STRUCTURE:

  \`\`\`
  app/                        # App screens
  ├── (tabs)/
  │    ├── index.tsx          # Root tab IMPORTANT
  │    └── _layout.tsx        # Root tab layout
  ├── _layout.tsx             # Root layout
  ├── assets/                 # Static assets
  ├── components/             # Shared components
  ├── hooks/  
      └── useFrameworkReady.ts
  ├── constants/              # App constants
  ├── app.json                # Expo config
  ├── expo-env.d.ts           # Expo environment types
  ├── tsconfig.json           # TypeScript config
  └── package.json            # Package dependencies
  \`\`\`

  TROUBLESHOOTING:

  1. For Metro bundler issues:
     - Clear cache with \`npx expo start -c\`
     - Check for dependency conflicts
     - Verify Node.js version compatibility

  2. For TypeScript errors:
     - Ensure proper typing
     - Update tsconfig.json as needed
     - Use type assertions sparingly

  3. For native module issues:
     - Verify Expo compatibility
     - Use Expo's prebuild feature for custom native code
     - Consider upgrading to Expo's dev client for testing
</mobile_app_instructions>
`,
};
